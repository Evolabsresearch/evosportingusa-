function visibleText(html) {
  const $ = cheerio.load(html);
  $("script, style, noscript, svg").remove();
  const body = $("body").clone();
  body.find("*").append(" ");
  return body.text().replace(/\s+/g, " ").trim();
}

async function fetchRoute(route) {
  const response = await fetch(`${baseUrl}${route}`);
  if (!response.ok) {
    throw new Error(`${route} returned ${response.status}`);
  }
  return response.text();
}

const failures = [];

for (const route of routes) {
  const text = visibleText(await fetchRoute(route));
  for (const term of bannedVisibleTerms) {
    if (text.toLowerCase().includes(term.toLowerCase())) {
      failures.push(`${route}: ${term}`);
    }
  }
}

if (failures.length) {
  throw new Error(`Public copy verification failed:\n${failures.join("\n")}`);
}

console.log(`Public copy verification passed: ${routes.length} routes checked.`);
